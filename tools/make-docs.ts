// Writes the MCP tool reference from the live tool definitions, so the docs cannot drift from the code.
import fs from 'node:fs';
import path from 'node:path';
import { z } from 'zod';
import { ALL_TOOLS } from '../src/core/tools.ts';

function fieldType(s: any): string {
  if (!s) return 'any';
  if (s.enum) return s.enum.map((x: unknown) => JSON.stringify(x)).join(' | ');
  const any = s.anyOf ?? s.oneOf;
  if (any) return [...new Set(any.map(fieldType))].join(' | ');
  if (s.type === 'array') return `${fieldType(s.items)}[]`;
  if (s.type === 'object') return 'object';
  return Array.isArray(s.type) ? s.type.join(' | ') : (s.type ?? 'any');
}

const lines: string[] = [];
lines.push('# MCP tool reference', '', 'Generated by `npm run docs` from the tool definitions. Every tool takes an `action` and that action\'s fields. Positions are beats (0-based numbers) or `"bar:beat"` strings.', '');
let actions = 0;
for (const t of ALL_TOOLS) {
  lines.push(`## ${t.name}`, '', t.description, '');
  for (const [name, def] of Object.entries(t.actions) as [string, any][]) {
    actions++;
    let props: Record<string, any> = {};
    let required: string[] = [];
    try {
      const js: any = z.toJSONSchema(def.schema, { io: 'input', unrepresentable: 'any' });
      props = js.properties ?? {};
      required = js.required ?? [];
    } catch { /* schemas with transforms can not always be rendered */ }
    delete props.action;
    lines.push(`### ${t.name} \`${name}\`${def.mutates ? ' · edits the project' : ''}`, '', def.description, '');
    const keys = Object.keys(props);
    if (keys.length) {
      lines.push('| field | type | notes |', '|---|---|---|');
      for (const k of keys) {
        const p = props[k];
        const note = String(p.description ?? '').replace(/\|/g, '\|').replace(/\n/g, ' ');
        lines.push(`| \`${k}\`${required.includes(k) ? ' *' : ''} | ${fieldType(p).replace(/\|/g, '\|')} | ${note} |`);
      }
      lines.push('');
    }
  }
}
lines.push(`${ALL_TOOLS.length} tools, ${actions} actions. A star marks a required field.`, '');
const text = lines.join('\n');
const root = path.resolve(import.meta.dirname, '..');
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'mcp-tools.md'), text);
fs.mkdirSync(path.join(root, 'skills', 'music-studio', 'references'), { recursive: true });
fs.writeFileSync(path.join(root, 'skills', 'music-studio', 'references', 'tools.md'), text);
console.log(`docs/mcp-tools.md: ${ALL_TOOLS.length} tools, ${actions} actions, ${(text.length / 1024).toFixed(0)} KB`);
