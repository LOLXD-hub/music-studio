// Measures every instrument preset and writes src/engine/instruments/calibration.ts so presets share a loudness.
// Melodic targets: -22 dBFS RMS over the first 600 ms of a mezzo-forte note, averaged over three pitches.
// Drums: -9 dBFS peak for kick and snare.
import fs from 'node:fs';
import { INSTRUMENT_DEFS, createInstrument } from '../src/engine/instruments/index.ts';

const SR = 44100;
const TARGET_RMS = -22;
const TARGET_DRUM_PEAK = -9;

function render(type: string, preset: string, pitch: number, vel: number, seconds: number, hold: number) {
  const inst = createInstrument(type, SR, 7, preset)!;
  const N = Math.floor(SR * seconds);
  const L = new Float32Array(N);
  const R = new Float32Array(N);
  inst.noteOn(pitch, vel);
  let off = false;
  for (let i = 0; i < N; i += 128) {
    if (!off && i >= hold * SR) {
      inst.noteOff(pitch);
      off = true;
    }
    const e = Math.min(N, i + 128);
    inst.process(L.subarray(i, e), R.subarray(i, e), 0, e - i);
  }
  return { L, R };
}

const db = (x: number) => 20 * Math.log10(Math.max(x, 1e-9));

function pitchesFor(type: string, name: string): number[] {
  if (/bass|tuba|cello|trombone|bassoon|horn/i.test(name)) return [36, 48, 60];
  if (/violin|flute|oboe|soprano|glock|celesta|music box|kalimba|harp|bell/i.test(name)) return [60, 72, 84];
  return [48, 60, 72];
}

const trims: Record<string, number> = {};
const report: string[] = [];
for (const def of INSTRUMENT_DEFS) {
  if (def.type === 'sampler') continue;
  const perPreset: number[] = [];
  for (const name of Object.keys(def.presets)) {
    const vals: number[] = [];
    if (def.type === 'drums') {
      for (const p of [36, 38]) {
        const { L, R } = render(def.type, name, p, 100, 1, 0.5);
        let pk = 0;
        for (let i = 0; i < L.length; i++) pk = Math.max(pk, Math.abs(L[i]), Math.abs(R[i]));
        vals.push(TARGET_DRUM_PEAK - db(pk));
      }
    } else {
      for (const p of pitchesFor(def.type, name)) {
        const { L, R } = render(def.type, name, p, 96, 1.2, 1.0);
        const n = Math.floor(SR * 0.6);
        let s = 0;
        for (let i = 0; i < n; i++) s += L[i] * L[i] + R[i] * R[i];
        vals.push(TARGET_RMS - db(Math.sqrt(s / (2 * n))));
      }
    }
    const avg = vals.reduce((a, b) => a + b, 0) / vals.length;
    const clamped = Math.max(-14, Math.min(14, avg));
    const gain = Math.pow(10, clamped / 20);
    trims[`${def.type}/${name}`] = +gain.toFixed(4);
    perPreset.push(clamped);
    report.push(`${def.type.padEnd(12)} ${name.padEnd(28)} ${clamped >= 0 ? '+' : ''}${clamped.toFixed(1)} dB`);
  }
  perPreset.sort((a, b) => a - b);
  const med = perPreset[Math.floor(perPreset.length / 2)];
  trims[`${def.type}/*`] = +Math.pow(10, med / 20).toFixed(4);
}
console.log(report.join('\n'));
const body = Object.entries(trims).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join('\n');
const file = `// Generated by tools/calibrate.ts: per-preset output trims (linear gain) so presets sit at a comparable loudness.
// Do not edit by hand; re-run \`node tools/calibrate.ts\` after changing an instrument.

export const TRIMS: Record<string, number> = {
${body}
};

export function trimFor(type: string, preset?: string): number {
  if (preset) {
    const v = TRIMS[type + '/' + preset];
    if (v !== undefined) return v;
  }
  return TRIMS[type + '/*'] ?? 1;
}
`;
fs.writeFileSync(new URL('../src/engine/instruments/calibration.ts', import.meta.url), file);
console.log('\nwrote calibration.ts with', Object.keys(trims).length, 'entries');
